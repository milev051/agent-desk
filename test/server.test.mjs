test('stream parser prepoznaje tekst, alate i greške dobavljača', () => {
  assert.equal(parseEvent('claude', { type: 'stream_event', event: { type: 'content_block_delta', delta: { type: 'text_delta', text: 'Ćao' } } }).delta, 'Ćao');
  assert.equal(parseEvent('grok', { type: 'assistant', message: { content: [{ type: 'text', text: 'Odgovor' }] } }).text, 'Odgovor');
  assert.equal(parseEvent('claude', { type: 'result', is_error: true, result: 'Nema prijave' }).error, 'Nema prijave');
  const chat = { settings: { agent: 'grok', access: 'read' }, sessions: {} };
  assert.throws(() => command(chat, 'test', 'grok'), /samo Full access/);
});

test('Antigravity parser obrađuje delte, konačan tekst i greške čak uz SUCCESS',()=>{
 assert.equal(parseEvent('antigravity',{event:'init',conversation_id:'session-a'}).session,'session-a');
 assert.equal(parseEvent('antigravity',{event:'step_update',step_update:{step_type:'agent_response',text_delta:'OK'}}).delta,'OK');
 assert.equal(parseEvent('antigravity',{event:'result',result:{status:'SUCCESS',response:'OK',conversation_id:'session-a'}}).replace,'OK');
 assert.match(parseEvent('antigravity',{event:'result',result:{status:'ERROR',error:'Authentication required'}}).error,/Authentication/);
 assert.match(parseEvent('antigravity',{event:'step_update',step_update:{state:'FAILED',step_type:'tool',tool_info:{error:{message:'Failed write'}}}}).error,/Failed/);
});

test('tokeni koriste završne CLI događaje, čuvaju razlike keša i ne izmišljaju istoriju',()=>{
 const codex=parseEvent('codex',{type:'turn.completed',usage:{input_tokens:200,cached_input_tokens:150,output_tokens:20,reasoning_output_tokens:3}}).usage;
 assert.equal(codex.input,200);assert.equal(codex.cacheRead,150);assert.equal(codex.inputIncludesCache,true);assert.equal(codex.reasoning,3);
 const claude=parseEvent('claude',{type:'result',usage:{input_tokens:100,cache_read_input_tokens:300,cache_creation_input_tokens:40,output_tokens:10}}).usage;
 assert.equal(claude.inputIncludesCache,false);assert.equal(claude.input,100);assert.equal(claude.cacheWrite,40);assert.equal(claude.scope,'main-loop');
 assert.equal(parseEvent('claude',{type:'assistant',message:{id:'same-step',usage:{input_tokens:100}}}).usage,undefined);
 assert.equal(parseEvent('claude',{type:'result',usage:{input_tokens:-1,output_tokens:'unknown'}}).usage,undefined);
 assert.equal(parseEvent('grok',{type:'result',usage:{input_tokens:20,cache_read_input_tokens:30,output_tokens:8,reasoning_tokens:4}}).usage.reasoning,4);
 const agy=parseEvent('antigravity',{event:'result',result:{status:'SUCCESS',usage:{input_tokens:250,output_tokens:25,thinking_tokens:10,cache_read_tokens:100,total_tokens:285}}}).usage;
 assert.equal(agy.total,285);assert.equal(agy.inputIncludesCache,null);assert.equal(agy.cacheRead,100);assert.equal(agy.reasoning,10);
 assert.equal(agy.history,undefined);
});
